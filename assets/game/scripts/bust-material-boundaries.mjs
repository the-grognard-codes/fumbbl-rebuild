export function reviewedBustMaterial(id, x, y, rgba, current) {
  const regions = contours[id];
  if (!regions || !rgba[3]) return current;
  const [r, g, b] = rgba, light = .2126 * r + .7152 * g + .0722 * b;
  // Latest pink strokes explicitly revise the Goblin's left helmet lip and
  // the narrow painted socket below its spike. Keep the spike itself fixed.
  const goblinLip = id === 'orc-goblin-lineman-portrait' && [
    [[70,61],[74,60],[71,69],[68,80],[67,90],[63,95],[59,94],[58,91],[62,92],[64,88],[65,77],[68,67]],
    [[49,32],[53,35],[57,34],[60,31],[61,34],[58,38],[53,38],[49,35]],
  ].some(points => contains(x, y, points));
  if (goblinLip && light > 17)
    return current > 0 && current < 17 ? current : 1 + Math.max(0, Math.min(15, Math.round((light - 18) / 7)));
  const inRegion = name => regions[name]?.some(points => contains(x, y, points));
  if (inRegion('fixed')) return 0;
  const annotations = painted[id];
  const inPaint = name => annotations?.[name]?.some(points => contains(x, y, points));
  // Keep the darkest outline pixels and all fixed-material contours intact.
  if (light > 17 && inPaint('primary'))
    return current > 0 && current < 17 ? current : 1 + Math.max(0, Math.min(15, Math.round((light - 18) / 7)));
  if (light > 38 && inPaint('secondary'))
    return current >= 17 ? current : 17 + Math.max(0, Math.min(15, Math.round((light - 50) / 13)));
  // Ivory shading differs from warm skin; geometry confines this selector to trim.
  if (inRegion('ivory') && r >= g - 3 && g > b * 1.035 && r - g < 47 && light > 38)
    return current >= 17 ? current : 17 + Math.max(0, Math.min(15, Math.round((light - 50) / 13)));
  if (inRegion('orange') && r > g * 1.4 && g > b * 1.35 && r - g > 25 && light > 25)
    return current >= 17 ? current : 17 + Math.min(15, Math.round(light / 12));
  if (inRegion('primary') && !current && light > 17 && r < g * 1.45 && g < b * 1.65 && b > r * .5)
    return 1 + Math.max(0, Math.min(15, Math.round((light - 18) / 7)));
  return current;
}
