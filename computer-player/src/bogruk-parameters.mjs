export function validateParameters(parameters = {}) {
 if (!parameters || typeof parameters !== 'object' || Array.isArray(parameters)) throw Error('Invalid Bogruk parameters');
 for (const [key, value] of Object.entries(parameters)) {
  const range = PARAMETER_RANGES[key];
  if (!range || !Number.isFinite(value) || value < range[0] || value > range[1]) throw Error('Invalid Bogruk parameter: ' + key);
 }
 return Object.freeze({ ...BOGRUK_PARAMETERS, ...parameters });
}
